# 「热电」二字极易误吃：热电模块/热电偶/热电材料都是半导体器件，跟热电联产无关。
# 实测栽过：「杭州大和热磁电子…建设年产48万件热电模块项目」被算成 S 档硬货。
THERMO_FALSE = ('热电模块', '热电偶', '热电材料', '热电堆', '热电半导体', '致冷')
# 电源类项目：看规模，太小不做
POWER_W = ('光伏', '风电', '储能', '充电', '电站', '发电')

import invest_filter as IF   # 复用 grab_mw（上一版已调好，含「1300千瓦」「1.3MW」等写法）


def judge(name, usd=None):
    """返回 (tier, why)。tier: S / A / W / X / ''(=不确定)"""
    n = name or ''
    # 半导体热电件先拦，否则「热电模块」会被 S 档的「热电」吃掉
    if any(w in n for w in THERMO_FALSE):
        return 'X', '半导体热电件，非热电联产'
    if any(w in n for w in X_W):
        # 有些名字里「贸易」出现在子公司名里，但主体是建厂，例如
        # 「X公司通过香港贸易公司并购印尼镍矿」—— 这类要救回来，先看 S
        if not any(w in n for w in S_W):
            return 'X', '不相关行业'
    hit_s = [w for w in S_W if w in n]
    hit_a = [w for w in A_W if w in n]

    # 电源类先看规模：2000kW 的光伏电站对我们是零价值
    if any(w in n for w in POWER_W) and not hit_s:
        mw = IF.grab_mw(n)
        if mw is not None and mw < 20:
            return 'X', '电源项目仅 %gMW' % mw
        if mw is None and any(w in n for w in ('光伏', '风电', '储能')):
            return 'X', '电源项目规模未知'

    if hit_s:
        return 'S', '工程含：' + '/'.join(hit_s[:3])
    if hit_a:
        # A 档必须见到实体动作，光「在香港新设XX纺织有限公司」的持股平台不算 ——
        # 实测这类占了 A 档一半，全是「设立…（香港）有限公司」，没有任何产能描述。
        if any(w in n for w in A_BUILD_W):
            return 'A', '客户行业建厂：' + '/'.join(hit_a[:3])
        return 'W', '客户行业但无产能描述：' + '/'.join(hit_a[:3])
    return '', ''


# 金额门槛：太小的项目连差旅都不划算。美元计价，1e6 = 100 万美元
MIN_USD = 3000000   # 300 万美元


def main():
    p = os.path.join(ROOT, 'raw', 'invest_odi.json')
    d = json.load(open(p, encoding='utf-8'))
    items = d['items']
    from collections import Counter
    cnt = Counter()
    for x in items:
        t, why = judge(x['name'], x.get('usd'))
        x['tier'], x['why'] = t, why
        cnt[t or 'none'] += 1
    keep = [x for x in items if x['tier'] in ('S', 'A')]
    out = {
        'updated': d.get('updated'),
        'total': len(items),
        'nS': cnt['S'], 'nA': cnt['A'],
        'items': keep,
        'dropped': [x for x in items if x['tier'] not in ('S', 'A')],
    }
    json.dump(out, open(os.path.join(ROOT, 'raw', 'invest_odi_pick.json'), 'w',
                        encoding='utf-8'), ensure_ascii=False, indent=1)
    print('总 %d → S %d / A %d / X %d / 不确定 %d，保留 %d'
          % (len(items), cnt['S'], cnt['A'], cnt['X'], cnt['none'], len(keep)))
    print()
    print('=== S 档（工程本体是我们的活）%d 条 ===' % cnt['S'])
    for x in [i for i in items if i['tier'] == 'S'][:25]:
        print('  %s %-8s %s' % (x['date'], x['geo'], x['name'][:56]))
    print()
    print('=== A 档（客户行业建厂）%d 条 ===' % cnt['A'])
    for x in [i for i in items if i['tier'] == 'A'][:15]:
        print('  %s %-8s %s' % (x['date'], x['geo'], x['name'][:56]))
    print()
    print('=== X 档抽掉的一些（看是否合理）===')
    for x in [i for i in items if i['tier'] == 'X'][:15]:
        print('  %-16s %s' % (x['why'][:16], x['name'][:52]))


if __name__ == '__main__':
    main()
