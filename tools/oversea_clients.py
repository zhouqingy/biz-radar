def dedup(rows):
    """按 kw 去重（同一家的全称/简称只留一条主记录）。"""
    seen = set()
    out = []
    for r in rows:
        k = r['kw']
        if k in seen:
            continue
        seen.add(k)
        out.append(r)
    return out


