# 「推演句」剪除规则
#
# 我司的解读文字有固定套路：前半句说事实（金额、规模、地点），后半句说「这对我意味着什么」。
# 后半句是**推演**，不能当项目内容。列黑名单永远列不全——试过三次，每次都是
# 「通常配套」「建议跟踪（含海水淡化）」「必然配套」「确定性机会窗口」轮着漏。
#
# 所以改成认**句式特征**，而不是认具体词。三类特征：
#   ① 情态/推测词：通常、一般、往往、必然、势必、有望、预计将、可能…
#   ② 我方视角词：含义、意味着、机会窗口、建议、值得跟、可切入、我司、对我们…
#   ③ 括号补充：「（含海水淡化）」这种是我们自己加的注解
# 带任一特征的整句丢掉，只留事实句去匹配。
_SPLIT = re.compile(r'[。；;！!？?\n]')
_HEDGE = re.compile(
    r'通常|一般来讲|一般|往往|必然|势必|有望|或将|可能|预计将|预计|或许|大概'          # 推测
    r'|含义|意味着|机会|窗口|建议|值得|跟踪|切入|我司|对我|可望|应提前|需配套|确定性'   # 我方视角
    # 「信号强弱 / 研判」类（2026-10-22 补）
    #   恒力迪拜那条原文写着「这是名单中较弱的商机信号，但反映…其大连基地本身也是
    #   热电联产存量客户的典型」——整句是**研判**，跟迪拜这个项目一点关系没有，
    #   却因为句子里有「热电联产」被标成 cogen。所有「本身也是」「存量客户」
    #   这种回头看自家盘子的话，都不该算项目内容。
    r'|较弱|较强|信号|研判|存量客户|典型|反映'
)
_PROMO_PAT = [
    re.compile(r'[（(][^）)]*含海水淡化[^）)]*[）)]'),
]


def _facts(title, desc=''):
    """只取「事实句」，丢掉推演句。

    ⚠ 这里必须把 title 单独传进来，不能拼成一整段再切——踩过：
      拼成 `title + ' ' + desc` 之后，整段描述变成了「第一句」，
      而第一句按规则无条件保留，于是「海螺塔什干 9MW 余热发电」这种
      明明白白的事实，被后面那句「通常配套余热电站」一起带进过滤，
      结果事实句被判成推演句、整条变成「看不出」。
      正确做法：title 永远保留（标题里写的就是项目实况），desc 按句过滤。
    """
    keep = [title or '']
    for p in _SPLIT.split(desc or ''):
        if p.strip() and not _HEDGE.search(p):
            keep.append(p)
    t = '；'.join(keep)
    for pat in _PROMO_PAT:
        t = pat.sub('', t)
    return t


# 「液冷」单独判，不放进 CUT_RULES 的原因：
#   这个词歧义太大。「数据中心液冷方案」「GB300 液冷板材料」「液冷散热铜排」
#   是三种完全不同的东西，最后一种是**卖铜材**，跟我们没关系。
#   放进 waste 关键词测过一轮，结果「金田越南 3 万吨液冷散热铜排」
#   「海亮越南 GB300 液冷板材料」全被标成余热回收——两笔材料订单误判成 EPC 机会。
#   所以：出现「液冷」时，要先排除掉 材料/铜排/铜管/散热 这些「卖东西」的搭配，
#   剩下「高密液冷」「直接液冷」「液冷方案」才算余热切口。
_LIQCOOL = re.compile(r'液冷')
_LIQCOOL_NOISE = re.compile(
    r'液冷[^，,。；;、]{0,6}(板|铜排|铜管|散热|材料)|'
    r'(板|铜排|铜管|散热|材料)[^，,。；;、]{0,4}液冷')


def guess_cut(title, desc=''):
    """判断这条线索能切进我们哪一段业务。返回 CUTS 的 key，判不出返回 ''。
    ⚠ 这里栽过三次，都是同一个毛病：把「我司解读里的推演」当成了「项目内容」。
      ① water 用了「淡水/淡化」泛词 → 盛虹在新加坡设个公司也被标成海水淡化；
      ② waste 用了「余热」单字 → 64 条全打成余热回收，因为每条尾巴都写「通常会配套余热电站」；
      ③ power 用了「自备电站」→「KFM 二期扩产」被打成自备电站，原文明明是
         「矿山扩产**通常**同步配套重油/柴油自备电站」——一句通论。
      结论：**假阳性比漏判更糟**。用户照着标签去追业务，扑空一次就不信了。
      所以先用 _facts() 把推演句剪掉再匹配；宁可标「看不出」，也不给错标签。
    """
    t = _facts(title, desc)
    for k, kws in CUT_RULES:
        if any(w in t for w in kws):
            return k
    # 「液冷」单独判（不能放进 CUT_RULES，理由见下）
    if _LIQCOOL.search(t) and not _LIQCOOL_NOISE.search(t):
        return 'waste'
    return ''


def cut_of(title, desc='', manual=''):
    """对外统一入口：人工写的 cut 优先，否则关键词兜底。"""
    return manual or guess_cut(title, desc)

