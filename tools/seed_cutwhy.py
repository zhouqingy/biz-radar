def key(t):
    return (t or '')[:20]


def find(prefix, title):
    """前缀匹配：FIX 的键只写前 20 字，实际标题更长，不能整串等值比。"""
    t = title or ''
    return t.startswith(prefix) or prefix.startswith(t[:len(prefix)]) if t else False


def _items(d):
    return d.get('items', d) if isinstance(d, dict) else d


def main():
    hit, skip, miss = 0, 0, dict(FIX)
    for p in TARGETS:
        if not os.path.exists(p):
            continue
        d = json.load(open(p, encoding='utf-8'))
        # 两种结构：{clients:[{items:[...]}]} 和 [ {...} ] / {items:[...]}
        buckets = []
        cl = d.get('clients') if isinstance(d, dict) else None
        if isinstance(cl, list):
            buckets = [c.get('items') or [] for c in cl]
        else:
            buckets = [_items(d)]
        for arr in buckets:
            if not isinstance(arr, list):
                continue
            for x in arr:
                if not isinstance(x, dict):
                    continue
                t = x.get('title') or ''
                for k in FIX:
                    if k in miss and t.startswith(k):
                        del miss[k]
                    if t.startswith(k):
                        if x.get('cutWhy'):
                            skip += 1
                            break
                        x['cut'], x['cutWhy'] = FIX[k]
                        hit += 1
                        break
        json.dump(d, open(p, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print('补写 %d 条 · 已有跳过 %d 条' % (hit, skip))
    if miss:
        print('⚠ 未命中（标题改过？）：')
        for k in miss:
            print('   ', k)
    print('负面清单（故意不给切口，留档）：')
    for k, v in NEG.items():
        print('   ', k, '→', v)


if __name__ == '__main__':
    main()
