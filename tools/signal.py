def _hits(text, words):
    return [w for w in words if w in text]


def _cancelled(text):
    """命中排除词则整条丢掉。注意「规划」已移到 POLICY 里单独处理——
    因为「规划建设年产10万吨镍铁项目」是明确信号，不能因为带「规划」就否掉。"""
    return bool(_hits(text, EXCLUDE))


def detect_region(text):
    out = []
    for k, kws in REGION_KW.items():
        if any(w in text for w in kws):
            out.append(k)
    return out


def classify(text):
    """判一条新闻属于哪个业务切口。返回 (种子, 命中词列表, 排名)。顺序=优先级。"""
    for i, (seg, kws) in enumerate(TECH_CORE.items()):
        h = _hits(text, kws)
        if not h:
            continue
        # 数据中心特殊：必须同时有能源词，否则机房土建也算进来了
        if seg == 'datactr' and not _hits(text, DC_ENERGY):
            continue
        return seg, h, i
    return None, [], 99


def judge(news):
    """
    判定一条行业动态。返回 dict：
      sig     是否算业务信号
      lvl     信号强度 strong/mid/weak（越大越急）
      seg     业务切口
      kw      命中的工艺词（给用户看「为什么判进来」）
      region  涉及地区
      why     一句话说明（人话，不堆术语）
    """
    title = news.get('title') or news.get('t') or ''
    desc = news.get('desc') or news.get('sum') or ''
    text = title + ' ' + desc

    if _cancelled(text):
        return {'sig': False, 'lvl': '', 'seg': None, 'kw': [], 'region': [],
                'why': '属于服务/货物采购或非工程内容，不是我们的信号'}

    # 政策/方案类文档：里面有「扩建」「EPC」等词，但它是规则不是项目
    # ---- 政策/文件 vs 具体项目：这一步最容易误判，写清楚 ----
    # 踩过的坑：
    #   ①「上海市碳排放配额分配方案」——「配额」在 POLICY、但标题带「单位」，被 ENTITY 放过
    #   ②「《新型电力系统建设"十五五"规划》印发」——书名号+规划，正则没覆盖中文引号
    #   ③「浙江省督察整改销号」——「公示」被当成了动作
    # 现在改成三层拦截，宁可漏判也不误判（漏了只是少一条线索，误了会让人去跟一个不存在的项目）。
    _DOC = ('方案', '办法', '意见', '通知', '细则', '标准', '规范', '指南',
            '条例', '规定', '规划', '白皮书', '蓝皮书', '报告', '计划')
    _PROJ_EXEMPT = ('项目获核准', '项目核准', '项目开工', '项目投产', '项目中标',
                    '项目招标', '项目备案', '工程开工', '工程中标')
    # 层 1：标题以书名号/引号包裹 + 含文件类词 = 政策文件
    if re.search(r'[《【「]([^》】」]{2,40}(?:%s))[》】」]' % '|'.join(_DOC), title):
        return {'sig': False, 'lvl': '', 'seg': None, 'kw': [], 'region': [],
                'why': '政策/规划类文件，不是具体项目'}
    # 层 2：标题里出现文件类词，且不是「项目+动作」组合
    if (any(w in title for w in _DOC)) and (not any(w in title for w in _PROJ_EXEMPT)):
        return {'sig': False, 'lvl': '', 'seg': None, 'kw': [], 'region': [],
                'why': '政策/方案类文件，不是具体项目'}
    # 层 3：POLICY 词命中且没有项目实体
    # 用 title 判实体，不用全文 —— 督察整改稿正文里总会带「项目」二字，用全文等于没判
    if _hits(title, POLICY) and not _hits(title, ENTITY):
        return {'sig': False, 'lvl': '', 'seg': None, 'kw': [], 'region': [],
                'why': '政策/方案类文件，不是具体项目'}

    seg, kws, rank = classify(text)
    if not seg:
        return {'sig': False, 'lvl': '', 'seg': None, 'kw': [], 'region': [],
                'why': '没有命中我们的业务切口（有色冶炼/RKEF/电解铝/水泥窑余热/数据中心…）'}

    lvl, act = '', []
    for name, words in (('strong', ACT_STRONG), ('mid', ACT_MID), ('weak', ACT_WEAK)):
        a = _hits(text, words)
        if a:
            lvl, act = name, a
            break

    if not lvl:
        return {'sig': False, 'lvl': '', 'seg': seg, 'kw': kws[:3],
                'region': detect_region(text),
                'why': '提到「%s」，但没有建厂/扩产动作（开工、环评、签约、招标等），是存量新闻' % kws[0]}

    # 必须有项目实体，否则只是「行业趋势」而不是「某地要建厂」
    if not _hits(text, ENTITY):
        return {'sig': False, 'lvl': '', 'seg': seg, 'kw': kws[:3],
                'region': detect_region(text),
                'why': '命中了业务切口，但没有落到具体项目/厂/机组上，属于行业趋势不是建厂信号'}

    region = detect_region(text)
    seg_cn = {
        'youse': '有色冶炼供能', 'steelgas': '钢铁煤气发电', 'wasteheat': '余热余压利用',
        'cogen': '热电联产/集中供热', 'selfplant': '自备电厂/能源站', 'datactr': '数据中心供能',
    }.get(seg, seg)

    lvl_cn = {'strong': '已动土/已投产', 'mid': '已进程序', 'weak': '仅意向'}[lvl]
    where = '、'.join(region[:2]) if region else '地点未标明'
    why = '%s · %s —— 命中「%s」，动作是「%s」' % (where, seg_cn, kws[0], act[0])

    return {
        'sig': True, 'lvl': lvl, 'seg': seg, 'segcn': seg_cn,
        'kw': kws[:3], 'act': act[:2], 'region': region,
        'oversea': bool(set(region) & OVERSEA),
        'why': why,
    }


