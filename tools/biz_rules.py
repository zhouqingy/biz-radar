    # ── 护栏 W3：前端信号 × 主业主体（底稿 §三② 项目信息来源）────────
    #   环评/可研/招标计划 与「电厂/机组/焚烧发电」同现 → 是主业项目前端信号，留；
    #   与「污水厂/管网/道路」同现 → 仍是垃圾，交给下面的删除规则。
    FRONT = ['环评', '环境影响评价', '受理', '可研', '核准', '立项', '招标计划', '预公告']
    MAIN = ['电厂', '机组', '焚烧发电', '热电联产', '煤气发电', '余热发电', '能源站']
    if any(x in t for x in FRONT) and any(x in t for x in MAIN):
        return False, 'W3', '主业项目前端信号（信息来源，留）'
    # ── 已拍板规则 N13：存量主设备改造（2026-11-05 P1 裁决）──────────
    #   函数型判据，不是词表；护栏 W/W2/W3 已在上面先判。
    if 'N13' in active and _is_stock_rebuild(t):
        return True, 'N13', '存量主设备改造（我们做不了，§三① 已改「剔」）'
    # ── 11 类词表删除共性（2026-11-05 用户指令全部启用）──────────────
    #   回归：命中保留集 607/1320 = 46.0%；其中 202 条同类漏网用户已拍板删，
    #   151 条真误伤与边界项仍留库 —— 启用只影响此后新采集 / 新构建的数据。
    for code, name, kws in SEM_RULES:
        if code not in active:
            continue
        for k in kws:
            if k in t:
                return True, code, name + '（命中「' + k + '」）'
    return False, '', '未命中已启用的过滤规则'


