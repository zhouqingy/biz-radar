def _hit(text, kws):
    for k in kws:
        if k in text:
            return k
    return None


def judge(title, snip='', amt=None, st='', buyer='', win=''):
    """单条记录的完整判定。采集层和构建层都调这里，口径不可能不一致。

    返回 dict:
      keep        是否入库（False = 连库都不进，纯噪声）
      investable  能否进「找商机」页签
      side        是否兼营（三级分公司业务）
      seg         业务层级 code
      segname     层级名
      mode        承包模式：EPC/EP/PC/E/F/O/GC/none
      bucket      tender / win / lead
      drop        被剔原因（investable=False 时）
      signal      前端信号词（有值说明是有效线索）
      rebuild     主机改造词（有值说明动主设备）
    """
    t = title or ''
    s = (title or '') + ' ' + (snip or '')
    r = {'keep': True, 'investable': True, 'side': False, 'seg': 'other',
         'segname': '其他', 'mode': '', 'bucket': 'tender', 'drop': '',
         'signal': '', 'rebuild': '', 'mainEquip': '', 'oversea': False}

    # ── ① 业务层级 ──────────────────────────────────────────────
    c = SM.classify(s)
    r['seg'], r['segname'] = c['seg'], c['segname']

    # ── ①b 设备返厂/维修：最高优先级硬剔除，先于一切判断 ──────────
    fb = _hit(t, FACTORY_BACK)
    if fb:
        r['investable'] = False
        r['drop'] = '设备返厂/维修类：' + fb

    # ── ② 承包模式 ──────────────────────────────────────────────
    if _hit(t, MODE_EPC):
        r['mode'] = 'EPC'
    elif _hit(t, MODE_F):
        r['mode'] = 'F'
    elif _hit(t, MODE_O):
        r['mode'] = 'O'
    elif _hit(t, MODE_PC):
        r['mode'] = 'PC'
    elif _hit(t, MODE_EP):
        r['mode'] = 'EP'
    elif _hit(t, MODE_E):
        r['mode'] = 'E'
    elif _hit(t, MODE_GC):
        # 施工总承包：内容有 E 或 P 的实据 → 实为 EPC，留；两者皆无 → 纯施工，剔
        if _hit(s, EVID_E) or _hit(s, EVID_P):
            r['mode'] = 'GC/EPC'
        else:
            r['mode'] = 'GC'
            r['investable'] = False
            r['drop'] = '纯施工总承包（无设计无采购）'

    # ── ③ 前端信号：留，归立项线索 ───────────────────────────────
    sig = _hit(t, SIGNAL_FRONT)
    if sig:
        r['signal'] = sig
        r['bucket'] = 'lead'
        if not r['mode']:
            r['mode'] = 'SIGNAL'

    # ── ④ 主机改造：留。动主设备的改造不是管网改造 ─────────────────
    me = _hit(t, MAIN_EQUIP)
    rb = _hit(t, REBUILD_MARK)
    if me and rb:
        r['mainEquip'] = me
        r['rebuild'] = rb

    # ── ⑤ 硬剔除：纯货物 / 后勤 ──────────────────────────────────
    hd = _hit(t, HARD_DROP)
    if hd and not _hit(t, MODE_EPC):
        r['investable'] = False
        r['drop'] = '纯货物/后勤：' + hd

    # ── ⑥ 分包施工单项：剔 ───────────────────────────────────────
    sc = _hit(t, SUBCONTRACT)
    if sc and not _hit(t, MODE_EPC + MODE_EP + MODE_PC + MODE_F + MODE_O):
        r['investable'] = False
        r['drop'] = r['drop'] or ('分包施工单项：' + sc)

    # ── ⑦ 管网类：剔。但主机改造优先（动主设备的不算管网） ──────────
    pw = _hit(t, PIPE_WORK)
    if pw and not r['rebuild']:
        r['investable'] = False
        r['drop'] = r['drop'] or ('管网类：' + pw)

    # ── ⑧ 后期服务/运维：不进找商机，但进同业/客户 ──────────────────
    ls = _hit(t, LATE_SERVICE)
    if ls and not r['rebuild'] and not _hit(t, MODE_EPC):
        r['investable'] = False
        r['drop'] = r['drop'] or ('后期服务：' + ls)

    # ── ⑨ 兼营：三级业务 ─────────────────────────────────────────
    if r['seg'] in ('soil', 'zero', 'sewage'):
        r['side'] = True
        r['investable'] = False
        r['drop'] = r['drop'] or ('兼营（分公司业务）：' + r['segname'])

    # ── ⑨b 不在 12 个业务层级内 → 不进找商机，但进同业/客户 ──────────
    #    2026-10-23 补：首跑发现 377 条 seg=other 混进了「找商机」。
    #    原因是 other 只在「无业主无中标单位」时才判不入库，一旦有业主就
    #    既进了库又进了找商机——等于「杭州地铁刮沙除尘地垫」这种只要有业主
    #    就能堂而皇之躺在找商机里。业务层级都没命中的，凭什么说能投。
    if r['seg'] == 'other':
        r['investable'] = False
        r['drop'] = r['drop'] or '不在12个业务层级内'

    # ── ⑨c 出海 → 走独立「海外机会」页签，不混进找商机 ──────────────
    #    用户 2026-10-23：海外独立页签。且海外不受地域限制（开发阶段）。
    if r['seg'] == 'oversea':
        r['oversea'] = True
        r['investable'] = False
        r['drop'] = r['drop'] or '海外（走海外机会页签）'

    # ── ⑩ 是否入库：完全无业务归属且无对手无业主 → 纯噪声，不进 ──────
    if r['seg'] == 'other' and not buyer and not win:
        r['keep'] = False
        r['investable'] = False
        r['drop'] = '纯噪声：无业务归属、无业主、无中标单位'

    # ── ⑪ 分档：信号类归 lead，其余按阶段 ─────────────────────────
    if r['bucket'] != 'lead':
        if st in ('中标结果公示', '中标候选人公示', '成交公告', '合同公告'):
            r['bucket'] = 'win'
        elif st in ('立项公示',):
            r['bucket'] = 'lead'
        else:
            r['bucket'] = 'tender'

    return r


